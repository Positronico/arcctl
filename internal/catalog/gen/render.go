const (
	generatedBy = "Code generated by internal/catalog/gen from internal/catalog/facts. DO NOT EDIT."
	verifiedBy  = "Code generated by internal/catalog/gen from internal/catalog/verified.json. DO NOT EDIT."
)

type output struct {
	path string
	data []byte
}

var renderers = []struct {
	path   string
	render func(*facts) ([]byte, error)
}{
	{"internal/catalog/zz_generated.go", renderCatalog},
	{"internal/keys/zz_hr.go", renderKeys},
	{"internal/keys/zz_presets.go", renderPresets},
	{"internal/keys/zz_consumer.go", renderConsumer},
	{"internal/mouse/zz_offsets.go", renderMouse},
	{"internal/keyboard/zz_offsets.go", renderKeyboard},
	{"packaging/linux/70-arcctl.rules", renderUdev},
}

func generate(f *facts) ([]output, error) {
	out := make([]output, 0, len(renderers))
	for _, r := range renderers {
		data, err := r.render(f)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", r.path, err)
		}
		out = append(out, output{r.path, data})
	}
	return out, nil
}

type gofile struct {
	bytes.Buffer
}

func newGoFile(pkg string, imports ...string) *gofile {
	return newGoFileBy(generatedBy, pkg, imports...)
}

func newGoFileBy(header, pkg string, imports ...string) *gofile {
	g := &gofile{}
	g.p("// %s", header)
	g.p("")
	g.p("package %s", pkg)
	for _, imp := range imports {
		g.p("")
		g.p("import %q", imp)
	}
	return g
}

func (g *gofile) p(format string, args ...any) {
	fmt.Fprintf(&g.Buffer, format, args...)
	g.WriteByte('\n')
}

func (g *gofile) raw(s string) {
	g.WriteString(s)
}

func (g *gofile) list(items []string, perLine int) {
	for i := 0; i < len(items); i += perLine {
		g.p("%s,", strings.Join(items[i:min(i+perLine, len(items))], ", "))
	}
}

func (g *gofile) source() ([]byte, error) {
	return format.Source(g.Bytes())
}

func q(s string) string { return strconv.Quote(s) }

func hex8(v uint8) string { return fmt.Sprintf("0x%02X", v) }

func hex16(v uint16) string { return fmt.Sprintf("0x%04X", v) }

func mapList[T any](items []T, f func(T) string) []string {
	out := make([]string, len(items))
	for i, it := range items {
		out[i] = f(it)
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	return slices.Sorted(maps.Keys(m))
}

func exported(name string) string {
	if name == "" {
		return ""
	}
	r, n := utf8.DecodeRuneInString(name)
	return string(unicode.ToUpper(r)) + name[n:]
}

func modelKey(m model) string {
	return fmt.Sprintf("%02X%02X", m.CID, m.MIDs[0])
}

func sensorVar(id string) string { return "sensor" + id }

var groupConst = map[string]string{
	"mouse":       "GroupMouse",
	"officeMouse": "GroupOfficeMouse",
	"keyboard":    "GroupKeyboard",
}

func renderCatalog(f *facts) ([]byte, error) {
	g := newGoFile("catalog")
	g.p("")
	g.p("const (")
	g.p("FactsSchema = %d", f.Sources.Schema)
	g.p("CfgVersion = %s", q(f.Sources.CfgVersion))
	g.p("Bundle = %s", q(f.Sources.Bundle))
	g.p(")")

	g.p("")
	g.p("var tools = []Tool{")
	for _, t := range f.Sources.Tools {
		fields := []string{"Name: " + q(t.Name)}
		if t.Version != nil {
			fields = append(fields, "Version: "+q(*t.Version))
		}
		if t.SHA256 != nil {
			fields = append(fields, "SHA256: "+q(*t.SHA256))
		}
		g.p("{%s},", strings.Join(fields, ", "))
	}
	g.p("}")

	g.p("")
	g.p("var inputs = []Input{")
	for _, in := range f.Sources.Inputs {
		g.p("{Path: %s, SHA256: %s},", q(in.Path), q(in.SHA256))
	}
	g.p("}")

	g.p("")
	g.p("var vendorIDs = []uint16{%s}", strings.Join(mapList(f.IDs.VIDs, hex16), ", "))
	g.p("")
	g.p("var productIDs = []productID{")
	for _, cl := range pidClasses(&f.IDs) {
		class := "Class" + exported(cl.name)
		for _, pid := range slices.Concat(cl.class.Wireless, cl.class.Wired) {
			g.p("{%s, %s},", hex16(pid), class)
		}
	}
	g.p("}")

	g.p("")
	g.p("var (")
	for _, s := range f.Sensors.Sensors {
		g.p("%s = &Sensor{", sensorVar(s.ID))
		g.p("ID: %s,", q(s.ID))
		g.p("Ranges: []Range{")
		for _, r := range s.Ranges {
			g.p("{Min: %d, Max: %d, Step: %d, DPIEx: %s},", r.Min, r.Max, r.Step, hex8(r.DPIEx))
		}
		g.p("},")
		if s.Values != nil {
			g.p("Values: []uint16{")
			g.list(mapList(s.Values, strconv.Itoa), 16)
			g.p("},")
		}
		if gates := sensorGates(f, s.ID); len(gates) > 0 {
			g.p("Gates: []string{%s},", strings.Join(mapList(gates, q), ", "))
		}
		g.p("}")
	}
	g.p(")")
	g.p("")
	g.p("var sensors = []*Sensor{%s}", strings.Join(mapList(f.Sensors.Sensors, func(s sensor) string { return sensorVar(s.ID) }), ", "))

	g.p("")
	g.p("var usages = []Usage{")
	for _, u := range f.Media.Usages {
		g.p("{Code: %s, Name: %s, Label: %s},", hex16(u.Code), q(u.Name), q(u.Label))
	}
	g.p("}")
	g.p("")
	g.p("var mouseMedia = []uint16{")
	g.list(mapList(f.Media.Mouse, hex16), 8)
	g.p("}")
	g.p("")
	g.p("var keyboardMedia = []uint16{")
	g.list(mapList(f.Media.Keyboard, hex16), 8)
	g.p("}")

	g.p("")
	g.p("var labels = map[string]string{")
	for _, k := range sortedKeys(f.Labels.Labels) {
		g.p("%s: %s,", q(k), q(f.Labels.Labels[k]))
	}
	g.p("}")

	g.p("")
	g.p("var factModels = []*Model{")
	for _, m := range f.Models.Models {
		renderModel(g, f, m)
	}
	g.p("}")
	return g.source()
}

func sensorGates(f *facts, id string) []string {
	var names []string
	for _, gt := range f.Sensors.Gates {
		if slices.Contains(gt.Sensors, id) {
			names = append(names, gt.Name)
		}
	}
	return names
}

func mediaLabel(f *facts, code uint16) string {
	i := slices.IndexFunc(f.Media.Usages, func(u usage) bool { return u.Code == code })
	return f.Media.Usages[i].Label
}

func renderModel(g *gofile, f *facts, m model) {
	g.p("{")
	g.p("Key: %s,", q(modelKey(m)))
	if m.Name != nil {
		g.p("Name: %s,", q(*m.Name))
	}
	g.p("Group: %s,", groupConst[m.Group])
	g.p("CID: %s,", hex8(m.CID))
	g.p("MIDs: []byte{%s},", strings.Join(mapList(m.MIDs, hex8), ", "))
	if m.Mouse != nil {
		renderMouseModel(g, f, m.Mouse)
	} else {
		renderKeyboardModel(g, m.Keyboard)
	}
	g.p("},")
}

func renderMouseModel(g *gofile, f *facts, mo *mouse) {
	g.p("Family: FamilyMouse,")
	g.p("Sensor: %s,", sensorVar(mo.Sensor))
	g.p("MaxDPI: %d,", mo.MaxDPI)
	g.p("Stages: %d,", len(mo.DPIs))
	g.p("Buttons: []Button{")
	for _, k := range mo.Keys {
		fields := []string{
			"Slot: " + strconv.Itoa(k.Index),
			"Type: " + hex8(k.Type),
			"Param: " + hex16(k.Param),
		}
		label := ""
		if k.Media != nil {
			fields = append(fields, "Media: "+hex16(*k.Media))
			label = mediaLabel(f, *k.Media)
		} else {
			label = f.Labels.Labels[*k.Label]
		}
		fields = append(fields, "Visible: "+strconv.FormatBool(k.Visible), "Label: "+q(label))
		g.p("{%s},", strings.Join(fields, ", "))
	}
	g.p("},")
	g.p("LongRangeDefault: ref(%t),", mo.LongDistance)
	g.p("Defaults: &MouseDefaults{")
	g.p("DPIs: []DPIStage{")
	for _, d := range mo.DPIs {
		g.p("{DPI: %d, Color: [3]byte{%s}},", d.DPI, strings.Join(mapList(d.Color[:], hex8), ", "))
	}
	g.p("},")
	g.p("CurrentDPI: %d,", mo.CurrentDPI)
	g.p("Debounce: %d,", mo.Debounce)
	g.p("TipsDebounce: %d,", mo.TipsDebounce)
	g.p("MaxDebounce: %d,", mo.MaxDebounce)
	g.p("ReportRate: %d,", mo.ReportRate)
	g.p("SensorMode: %d,", mo.SensorMode)
	if mo.LOD != nil {
		g.p("LOD: ref(%d),", *mo.LOD)
	}
	g.p("PerformanceState: %t,", mo.PerformanceState)
	g.p("Performance: %d,", mo.Performance)
	g.p("Ripple: %t,", mo.Ripple)
	g.p("Angle: %t,", mo.Angle)
	g.p("MotionSync: %t,", mo.MotionSync)
	g.p("SleepTime: %d,", mo.SleepTime)
	e := mo.DPIEffect
	g.p("DPIEffect: DPIEffect{Mode: %d, Brightness: %d, Speed: %d, Show: %t},", e.Mode, e.Brightness, e.Speed, e.Show)
	l := mo.LightEffect
	g.p("LightEffect: LightEffect{Mode: %d, Brightness: %d, Speed: %d, MovingOffState: %t},", l.Mode, l.Brightness, l.Speed, l.MovingOffState)
	if mo.Firmware != nil {
		g.p("Firmware: map[string]string{")
		for _, k := range sortedKeys(mo.Firmware) {
			g.p("%s: %s,", q(k), q(mo.Firmware[k]))
		}
		g.p("},")
	}
	g.p("},")
}

func renderKeyboardModel(g *gofile, kb *keyboard) {
	g.p("Family: FamilyKeyboard,")
	g.p("Keyboard: &KeyboardSpec{")
	g.p("Systems: []string{%s},", strings.Join(mapList(kb.Systems, q), ", "))
	g.p("Layouts: []string{%s},", strings.Join(mapList(kb.Layouts, q), ", "))
	g.p("Width: %d,", kb.Image.Width)
	g.p("Height: %d,", kb.Image.Height)
	g.p("Rects: []Rect{")
	g.list(mapList(kb.Rects, func(r rect) string {
		return fmt.Sprintf("{%d, %d, %d, %d}", r.Left, r.Top, r.Width, r.Height)
	}), 8)
	g.p("},")
	g.p("Maps: []Layer{")
	for _, l := range kb.Maps {
		g.p("{")
		g.p("System: %s,", q(l.System))
		g.p("Layout: %s,", q(l.Layout))
		g.p("Slots: []KeySlot{")
		g.list(mapList(l.Slots, func(s keySlot) string {
			return fmt.Sprintf("{%s, %s}", hex8(s.Type), hex16(s.Value))
		}), 8)
		g.p("},")
		g.p("},")
	}
	g.p("},")
	g.p("},")
}

func keyLiteral(k key) string {
	return fmt.Sprintf("{%s, %d, %s, %s, %s}", q(k.Code), k.Kind, hex8(k.Value), q(k.Win), q(k.Mac))
}

func renderKeys(f *facts) ([]byte, error) {
	g := newGoFile("keys", "slices")
	g.raw(`
type Kind uint8

type Key struct {
	Code  string
	Kind  Kind
	Value uint8
	Win   string
	Mac   string
}

func All() []Key { return slices.Clone(hr[:]) }

func ByCode(code string) (Key, bool) {
	for _, k := range hr {
		if k.Code == code {
			return k, true
		}
	}
	return Key{}, false
}

func ByValue(kind Kind, value uint8) (Key, bool) {
	for _, k := range hr {
		if k.Kind == kind && k.Value == value {
			return k, true
		}
	}
	return Key{}, false
}
`)
	g.p("var hr = [...]Key{")
	for _, k := range f.Keys.Keys {
		g.p("%s,", keyLiteral(k))
	}
	g.p("}")
	return g.source()
}

func renderPresets(f *facts) ([]byte, error) {
	g := newGoFile("keys", "slices")
	g.raw(`
type Preset struct {
	ID    string
	Label string
	Keys  []Key
}

type RepeatMode uint8
`)
	g.p("const (")
	for i, m := range repeatModes {
		if i == 0 {
			g.p("Repeat%s RepeatMode = iota", exported(m))
		} else {
			g.p("Repeat%s", exported(m))
		}
	}
	g.p(")")
	g.raw(`
type RepeatOption struct {
	Value uint8
	Mode  RepeatMode
	Label string
}

func WinPresets() []Preset { return clonePresets(winPresets[:]) }

func MacPresets() []Preset { return clonePresets(macPresets[:]) }

func RepeatOptions() []RepeatOption { return slices.Clone(repeatOptions[:]) }

func clonePresets(ps []Preset) []Preset {
	out := make([]Preset, len(ps))
	for i, p := range ps {
		p.Keys = slices.Clone(p.Keys)
		out[i] = p
	}
	return out
}
`)
	byCode := map[string]key{}
	for _, k := range f.Keys.Keys {
		byCode[k.Code] = k
	}
	for _, set := range presetSets(&f.Presets) {
		g.p("var %sPresets = [...]Preset{", set.os)
		for _, pr := range set.presets {
			g.p("{ID: %s, Label: %s, Keys: []Key{", q(pr.ID), q(f.Labels.Labels[pr.Label]))
			for _, pk := range pr.Keys {
				g.p("%s,", keyLiteral(byCode[pk.Code]))
			}
			g.p("}},")
		}
		g.p("}")
		g.p("")
	}
	g.p("var repeatOptions = [...]RepeatOption{")
	for _, r := range f.Presets.MacroRepeat {
		g.p("{Value: %d, Mode: Repeat%s, Label: %s},", r.Value, exported(r.Mode), q(f.Labels.Labels[r.Label]))
	}
	g.p("}")
	return g.source()
}

func renderConsumer(f *facts) ([]byte, error) {
	g := newGoFile("keys", "slices")
	g.raw(`
type Consumer struct {
	Usage uint16
	Name  string
	Label string
}

func ConsumerByUsage(usage uint16) (Consumer, bool) {
	i, ok := slices.BinarySearchFunc(consumers[:], usage, func(c Consumer, u uint16) int { return int(c.Usage) - int(u) })
	if !ok {
		return Consumer{}, false
	}
	return consumers[i], true
}
`)
	g.p("var consumers = [...]Consumer{")
	for _, u := range f.Media.Usages {
		g.p("{%s, %s, %s},", hex16(u.Code), q(u.Name), q(u.Label))
	}
	g.p("}")
	return g.source()
}

func renderMouse(f *facts) ([]byte, error) {
	g := newGoFile("mouse")
	g.p("")
	g.p("const (")
	for _, o := range f.Offsets.Mouse {
		if o.Value != nil {
			g.p("Addr%s = %d", exported(o.Name), *o.Value)
		}
	}
	g.p(")")
	levels := slices.Clone(f.Brightness.Levels)
	slices.SortFunc(levels, func(a, b brightnessLevel) int { return a.Level - b.Level })
	g.p("")
	g.p("func DPILightBrightness(level int) byte {")
	g.p("switch level {")
	for _, l := range levels {
		g.p("case %d:", l.Level)
		g.p("return %d", l.Value)
	}
	g.p("}")
	g.p("return %d", f.Brightness.Default)
	g.p("}")
	g.p("")
	g.p("func DPILightLevel(b byte) (int, bool) {")
	g.p("switch b {")
	for _, l := range levels {
		g.p("case %d:", l.Value)
		g.p("return %d, true", l.Level)
	}
	g.p("}")
	g.p("return 0, false")
	g.p("}")
	return g.source()
}

func renderKeyboard(f *facts) ([]byte, error) {
	g := newGoFile("keyboard")
	tables := offsetTables(&f.Offsets)[1:]
	var fields []string
	for _, t := range tables {
		for _, o := range t.entries {
			if name := exported(o.Name); !slices.Contains(fields, name) {
				fields = append(fields, name)
			}
		}
	}
	g.p("")
	g.p("const NoOffset = -1")
	g.p("")
	g.p("type Offsets struct {")
	for _, name := range fields {
		g.p("%s int", name)
	}
	g.p("}")
	for i, fn := range []string{"StandardOffsets", "OfficeOffsets"} {
		values := map[string]string{}
		for _, o := range tables[i].entries {
			if o.Value != nil {
				values[exported(o.Name)] = strconv.Itoa(*o.Value)
			}
		}
		g.p("")
		g.p("func %s() Offsets {", fn)
		g.p("return Offsets{")
		for _, name := range fields {
			v, ok := values[name]
			if !ok {
				v = "NoOffset"
			}
			g.p("%s: %s,", name, v)
		}
		g.p("}")
		g.p("}")
	}
	return g.source()
}

func renderUdev(f *facts) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\n\n", generatedBy)
	for _, vid := range f.IDs.VIDs {
		for _, cl := range pidClasses(&f.IDs) {
			for _, pid := range slices.Concat(cl.class.Wireless, cl.class.Wired) {
				fmt.Fprintf(&b, "SUBSYSTEM==\"hidraw\", ATTRS{idVendor}==\"%04x\", ATTRS{idProduct}==\"%04x\", TAG+=\"uaccess\"\n", vid, pid)
			}
		}
	}
	return b.Bytes(), nil
}
